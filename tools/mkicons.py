#!/usr/bin/env python3
"""Draw the desktop's icons (Files, System, Notes, Display) into main/icons_aa.c.

Each icon is an anti-aliased 4-bit alpha mask, drawn at 8x and scaled down, so the app can
ink it in any colour on the launcher's discs.
"""
from PIL import Image, ImageDraw

SIZE = 34          # pixels on the desktop
S = 8              # supersampling
N = SIZE * S


def u(v):
    return int(v * N / 100)


def files(d):
    # A folder: a tab and a body, rounded.
    d.rounded_rectangle((u(6), u(18), u(46), u(36)), radius=u(6), fill=255)
    d.rounded_rectangle((u(6), u(28), u(94), u(84)), radius=u(9), fill=255)
    d.rounded_rectangle((u(6), u(40), u(94), u(44)), radius=u(2), fill=0)


def system(d):
    # A chip: a body with a die and pins on all four sides.
    d.rounded_rectangle((u(22), u(22), u(78), u(78)), radius=u(8), fill=255)
    d.rounded_rectangle((u(36), u(36), u(64), u(64)), radius=u(4), fill=0)
    for i in range(4):
        p = u(28 + i * 14.5)
        w = u(6)
        d.rounded_rectangle((p, u(6), p + w, u(20)), radius=u(2), fill=255)
        d.rounded_rectangle((p, u(80), p + w, u(94)), radius=u(2), fill=255)
        d.rounded_rectangle((u(6), p, u(20), p + w), radius=u(2), fill=255)
        d.rounded_rectangle((u(80), p, u(94), p + w), radius=u(2), fill=255)


def notes(d):
    # A notepad: a page, three lines and a pencil across the corner.
    d.rounded_rectangle((u(14), u(6), u(76), u(94)), radius=u(9), fill=255)
    for i in range(3):
        y = u(30 + i * 18)
        d.rounded_rectangle((u(26), y, u(64), y + u(6)), radius=u(3), fill=0)
    d.line((u(58), u(84), u(92), u(50)), fill=0, width=u(20))
    d.line((u(60), u(82), u(90), u(52)), fill=255, width=u(11))
    d.polygon((u(52), u(92), u(56), u(78), u(66), u(88)), fill=255)


def display(d):
    # A monitor on a stand.
    d.rounded_rectangle((u(4), u(12), u(96), u(72)), radius=u(9), fill=255)
    d.rounded_rectangle((u(13), u(21), u(87), u(63)), radius=u(4), fill=0)
    d.rectangle((u(43), u(72), u(57), u(84)), fill=255)
    d.rounded_rectangle((u(26), u(82), u(74), u(90)), radius=u(4), fill=255)


ICONS = [("icon_files", files), ("icon_system", system), ("icon_notes", notes), ("icon_display", display)]

out = ["/* SPDX-License-Identifier: GPL-3.0-or-later */", "/**", " * @file icons_aa.c",
       " * @brief The desktop's icons as 4-bit alpha masks, %d x %d." % (SIZE, SIZE),
       " *        Generated by tools/mkicons.py; do not edit.", " */", '#include "icons_aa.h"', ""]
sheet = Image.new("L", (SIZE * len(ICONS) + 8 * (len(ICONS) - 1), SIZE), 0)
for k, (name, draw) in enumerate(ICONS):
    im = Image.new("L", (N, N), 0)
    draw(ImageDraw.Draw(im))
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    sheet.paste(im, (k * (SIZE + 8), 0))
    px = im.load()
    data = []
    for y in range(SIZE):
        for x in range(0, SIZE, 2):
            data.append(((px[x, y] >> 4) << 4) | (px[x + 1, y] >> 4))
    out.append("static const uint8_t %s_bits[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 17):
        out.append("    " + ", ".join("0x%02X" % v for v in data[i:i + 17]) + ",")
    out.append("};")
    out.append("const aa_icon_t %s = { %s_bits, %d, %d };" % (name, name, SIZE, SIZE))
    out.append("")
open("main/icons_aa.c", "w").write("\n".join(out))
sheet.resize((sheet.width * 4, sheet.height * 4), Image.NEAREST).save("tools/icons_preview.png")
print("ok")
