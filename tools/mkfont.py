#!/usr/bin/env python3
"""Turn a PSF console font (8 px wide) into main/font8x16.h: ASCII 32..126.

Used with Terminus (Lat15-Terminus16.psf.gz, SIL Open Font License 1.1).
"""
import gzip, sys

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-Terminus16.psf.gz"
d = gzip.open(path).read()
if d[:2] == b"\x36\x04":                       # PSF1
    h, n, cs, base, uni = 16, (512 if d[2] & 1 else 256), d[3], 4, d[2] & 2
    glyph = lambda i: d[base + i * cs: base + (i + 1) * cs]
    table = d[base + n * cs:] if uni else b""
else:                                          # PSF2
    import struct
    _, ver, hs, flags, n, cs, h, w = struct.unpack("<8I", d[:32])
    glyph = lambda i: d[hs + i * cs: hs + (i + 1) * cs]
    table = d[hs + n * cs:] if flags & 1 else b""
cs = len(glyph(0))
# map unicode -> glyph index (PSF1 table: u16 entries, 0xFFFF separates)
umap = {}
if table and d[:2] == b"\x36\x04":
    i = 0; g = 0
    while i + 1 < len(table) and g < n:
        u = table[i] | (table[i + 1] << 8); i += 2
        if u == 0xFFFF: g += 1; continue
        if u == 0xFFFE: continue
        umap.setdefault(u, g)
out = ["/* SPDX-License-Identifier: OFL-1.1 */",
       "/**", " * @file font8x16.h",
       " * @brief Terminus 8x16 (SIL Open Font License 1.1), ASCII 32..126, one byte per row.",
       " *        Generated by tools/mkfont.py; do not edit.", " */",
       "#ifndef FONT8X16_H_", "#define FONT8X16_H_", "#include <stdint.h>",
       "#define FONT8X16_FIRST 32", "#define FONT8X16_LAST 126",
       "static const uint8_t font8x16[95][16] = {"]
for c in range(32, 127):
    g = glyph(umap.get(c, c))[:16]
    out.append("    {" + ", ".join("0x%02X" % b for b in g) + "}, /* %r */" % chr(c))
out += ["};", "#endif /* FONT8X16_H_ */", ""]
open("main/font8x16.h", "w").write("\n".join(out))
print("ok", cs, h)
