#!/usr/bin/env python3
"""Rasterise Outfit (SIL OFL 1.1, tools/fonts/) into anti-aliased 4-bit bitmap fonts: main/fonts_aa.c.

Each font: ASCII 32..126, a glyph table (advance, box and offset from the pen at the top of
the line) and 4-bit alpha, two pixels a byte, rows padded to a whole byte.
"""
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # C name, weight, pixel size
    ("font_ui", b"Medium", 17),
    ("font_bold", b"SemiBold", 19),
    ("font_title", b"Bold", 26),
    ("font_big", b"ExtraBold", 56),
]
out = ["/* SPDX-License-Identifier: OFL-1.1 */",
       "/**", " * @file fonts_aa.c",
       " * @brief Outfit (SIL Open Font License 1.1, tools/fonts/OFL-Outfit.txt), anti-aliased, 4-bit.",
       " *        Generated by tools/mkfont_ttf.py; do not edit.", " */",
       '#include "fonts_aa.h"', ""]
for name, wght, size in FONTS:
    f = ImageFont.truetype("tools/fonts/Outfit.ttf", size)
    f.set_variation_by_name(wght)
    asc, desc = f.getmetrics()
    data = bytearray(); glyphs = []
    for c in range(32, 127):
        ch = chr(c)
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch)
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
            px = im.load()
            for y in range(h):
                for x in range(0, w, 2):
                    a = px[x, y] >> 4
                    b2 = (px[x + 1, y] >> 4) if x + 1 < w else 0
                    data.append((a << 4) | b2)
        glyphs.append((off, adv, w, h, l, t))
    out.append("static const uint8_t %s_bits[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join("0x%02X" % v for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append("static const aa_glyph_t %s_glyphs[95] = {" % name)
    for g in glyphs:
        out.append("    { %d, %d, %d, %d, %d, %d }," % g)
    out.append("};")
    out.append("const aa_font_t %s = { %s_bits, %s_glyphs, %d, %d };" % (name, name, name, asc + desc, asc))
    out.append("")
open("main/fonts_aa.c", "w").write("\n".join(out))
print("ok")
